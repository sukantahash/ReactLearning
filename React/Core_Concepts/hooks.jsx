// useState:
// Example:

import React, { useState } from 'react';

function Counter() {
  // Declare a new state variable, which we'll call "count"
  const [count, setCount] = useState(0);

  return (
    <div>
      <p>You clicked {count} times</p>
      <button onClick={() => setCount(count + 1)}>
        Click me
      </button>
    </div>
  );
}

export default Counter;


// Explanation
// Importing useState: First, you need to import useState from React.

// Declaring State: You call useState inside a functional component to declare a state variable.
//  In this example, count is the state variable, and setCount is the function used to update count.

// Initial State: The argument passed to useState (in this case, 0) is the initial state value.

// Updating State: You can update the state by calling the state updater function 
// (setCount in this example) with the new state value.


// Key Points

// Multiple State Variables: You can use multiple useState hooks to manage different pieces of state 
// within the same component.

// State Updates are Asynchronous: State updates using setCount are asynchronous, and React may batch 
// multiple updates for performance reasons.

